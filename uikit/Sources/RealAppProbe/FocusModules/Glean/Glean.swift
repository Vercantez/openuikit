public final class Glean: @unchecked Sendable {
    public static let shared = Glean()
    public private(set) var uploadEnabled = false
    public private(set) var initialized = false
    public private(set) var configuration: Configuration?
    public private(set) var lastCustomURL: URL?

    private init() {}

    public func initialize(
        uploadEnabled: Bool,
        configuration: Configuration = Configuration(),
        buildInfo: BuildInfo
    ) {
        _ = buildInfo
        self.uploadEnabled = uploadEnabled
        self.configuration = configuration
        self.initialized = true
    }

    public func setUploadEnabled(_ enabled: Bool) {
        uploadEnabled = enabled
    }

    public func handleCustomUrl(url: URL) {
        lastCustomURL = url
    }
}

public final class CounterMetricType: @unchecked Sendable {
    private let lock = NSLock()
    private var value: Int32 = 0
    public init() {}
    public func add(_ amount: Int32 = 1) {
        lock.lock()
        value += amount
        lock.unlock()
    }
    public func testGetValue() -> Int32 {
        lock.lock()
        defer { lock.unlock() }
        return value
    }
}

