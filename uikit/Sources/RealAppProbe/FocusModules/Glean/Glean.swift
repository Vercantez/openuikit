public final class EventMetricType<Extra>: @unchecked Sendable {
    private let lock = NSLock()
    private var extras: [Extra] = []
    public init() {}
    public func record(_ extra: Extra) {
        lock.lock()
        extras.append(extra)
        lock.unlock()
    }
    public func testGetCount() -> Int {
        lock.lock()
        defer { lock.unlock() }
        return extras.count
    }
}

extension EventMetricType where Extra == Void {
    public func record() { record(()) }
}

public final class LabeledMetricType<T>: @unchecked Sendable {
    private let lock = NSLock()
    private var labels: [String: T] = [:]
    private let make: () -> T
    public init(_ make: @escaping () -> T) {
        self.make = make
    }
    public subscript(label: String) -> T {
        lock.lock()
        defer { lock.unlock() }
        if let existing = labels[label] { return existing }
        let created = make()
        labels[label] = created
        return created
    }
}

