public struct Configuration {
    public var channel: String?
    public var dataPath: String?
    public var maxEvents: Int?
    public var logLevel: String?
    public var enableEventTimestamps: Bool
    public var experimentationId: String?

    public init(
        channel: String? = nil,
        dataPath: String? = nil,
        maxEvents: Int? = nil,
        logLevel: String? = nil,
        enableEventTimestamps: Bool = true,
        experimentationId: String? = nil
    ) {
        self.channel = channel
        self.dataPath = dataPath
        self.maxEvents = maxEvents
        self.logLevel = logLevel
        self.enableEventTimestamps = enableEventTimestamps
        self.experimentationId = experimentationId
    }
}

