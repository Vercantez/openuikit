static void cmyk_to_srgb(QZFloat c, QZFloat m, QZFloat y, QZFloat k,
                         QZFloat *r, QZFloat *g, QZFloat *b) {
    c = (QZFloat)qz::clampd(c, 0, 1);
    m = (QZFloat)qz::clampd(m, 0, 1);
    y = (QZFloat)qz::clampd(y, 0, 1);
    k = (QZFloat)qz::clampd(k, 0, 1);

    int ci[2], mi[2], yi[2], ki[2];
    double tc[2], tm[2], ty[2], tk[2];
    auto split = [](double v, int idx[2], double w[2]) {
        double x = v * 8.0;
        int i = (int)x;
        if (i >= 8) {
            idx[0] = idx[1] = 8;
            w[0] = 1;
            w[1] = 0;
            return;
        }
        idx[0] = i;
        idx[1] = i + 1;
        w[1] = x - i;
        w[0] = 1.0 - w[1];
    };
    split(c, ci, tc);
    split(m, mi, tm);
    split(y, yi, ty);
    split(k, ki, tk);

    double acc[3] = {0, 0, 0};
    for (int ic = 0; ic < 2; ic++) {
        for (int im = 0; im < 2; im++) {
            for (int iy = 0; iy < 2; iy++) {
                for (int ik = 0; ik < 2; ik++) {
                    double w = tc[ic] * tm[im] * ty[iy] * tk[ik];
                    if (w == 0) continue;
                    size_t base = (((((size_t)ci[ic] * 9 + (size_t)mi[im]) * 9 +
                                    (size_t)yi[iy]) * 9 + (size_t)ki[ik]) * 3);
                    acc[0] += w * (kCMYKtoSRGB[base + 0] * (1.0 / 65535.0));
                    acc[1] += w * (kCMYKtoSRGB[base + 1] * (1.0 / 65535.0));
                    acc[2] += w * (kCMYKtoSRGB[base + 2] * (1.0 / 65535.0));
                }
            }
        }
    }
    *r = (QZFloat)qz::clampd(acc[0], 0, 1);
    *g = (QZFloat)qz::clampd(acc[1], 0, 1);
    *b = (QZFloat)qz::clampd(acc[2], 0, 1);
}

QZColorSpaceRef QZColorSpaceCreateDeviceCMYK(void) {
    /* QZColor stores RGB; DeviceCMYK is converted at the API boundary. */
    return QZColorSpaceCreateDeviceRGB();
}

QZColorRef QZColorCreateGenericCMYK(QZFloat c, QZFloat m, QZFloat y, QZFloat k, QZFloat a) {
    QZFloat r, g, b;
    cmyk_to_srgb(c, m, y, k, &r, &g, &b);
    return QZColorCreateGenericRGB(r, g, b, a);
}

