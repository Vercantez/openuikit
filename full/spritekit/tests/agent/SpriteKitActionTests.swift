func testActionMoveAndFade() {
    let scene = SKScene(size: CGSize(width: 100, height: 100))
    let node = SKNode()
    scene.addChild(node)
    node.run(SKAction.move(to: CGPoint(x: 10, y: 20), duration: 0))
    scene.update(0)
    scene.update(1)
    precondition(abs(node.position.x - 10) < 0.001)
    node.run(SKAction.moveBy(x: 5, y: -5, duration: 0))
    scene.update(2)
    precondition(abs(node.position.x - 15) < 0.001)
    node.run(SKAction.move(by: CGVector(dx: 1, dy: 1), duration: 0))
    scene.update(3)
    node.run(SKAction.moveTo(x: 0, duration: 0))
    scene.update(4)
    node.run(SKAction.moveTo(y: 0, duration: 0))
    scene.update(5)
    node.alpha = 1
    node.run(SKAction.fadeOut(withDuration: 0))
    scene.update(6)
    precondition(node.alpha == 0)
    node.run(SKAction.fadeIn(withDuration: 0))
    scene.update(7)
    precondition(node.alpha == 1)
    node.run(SKAction.fadeAlpha(to: 0.25, duration: 0))
    scene.update(8)
    precondition(abs(node.alpha - 0.25) < 0.001)
    node.run(SKAction.fadeAlpha(by: 0.25, duration: 0))
    scene.update(9)
}

func testActionScaleRotateResize() {
    let scene = SKScene(size: CGSize(width: 40, height: 40))
