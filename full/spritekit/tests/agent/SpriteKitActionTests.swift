func testActionSequenceGroupRepeat() {
    let scene = SKScene(size: CGSize(width: 10, height: 10))
    let node = SKNode()
    scene.addChild(node)
    let seq = SKAction.sequence([
        SKAction.moveBy(x: 4, y: 0, duration: 0),
        SKAction.moveBy(x: 0, y: 4, duration: 0),
    ])
    node.run(seq)
    scene.update(0); scene.update(0.5); scene.update(1)
    let grouped = SKAction.group([
        SKAction.fadeAlpha(to: 0.5, duration: 0),
        SKAction.rotate(byAngle: 0.1, duration: 0),
    ])
    node.run(grouped)
    scene.update(2)
    node.run(SKAction.repeat(SKAction.moveBy(x: 1, y: 0, duration: 0), count: 2))
    scene.update(3); scene.update(4)
    let forever = SKAction.repeatForever(SKAction.wait(forDuration: 0))
    node.run(forever, withKey: "loop")
    precondition(node.action(forKey: "loop") != nil)
    precondition(node.hasActions())
    node.removeAction(forKey: "loop")
    node.removeAllActions()
    precondition(!node.hasActions())
}

func testActionHideWaitRun() {
    let scene = SKScene(size: CGSize(width: 8, height: 8))
    let node = SKNode()
    node.name = "child"
    scene.addChild(node)
    node.run(SKAction.hide())
    scene.update(0)
    precondition(node.isHidden)
    node.run(SKAction.unhide())
    scene.update(1)
    precondition(!node.isHidden)
    var ran = false
    node.run(SKAction.run { ran = true })
    scene.update(2)
    precondition(ran)
    let childAction = SKAction.run(SKAction.fadeOut(withDuration: 0), onChildWithName: "child")
    scene.run(childAction)
    scene.update(3)
    node.run(SKAction.wait(forDuration: 0))
    scene.update(4)
    node.run(SKAction.wait(forDuration: 0, withRange: 0))
    scene.update(5)
    var custom = 0 as CGFloat
    node.run(SKAction.customAction(withDuration: 0) { _, t in custom = t })
    scene.update(6)
    precondition(custom >= 0)
    let reversed = SKAction.moveBy(x: 2, y: 0, duration: 0).reversed()
    node.run(reversed)
    scene.update(7)
    _ = SKAction().copy()
}

