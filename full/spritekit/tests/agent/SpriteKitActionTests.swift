func testActionFollowReachWarp() {
    let path = CGPath(rect: CGRect(x: 0, y: 0, width: 10, height: 10))
    _ = SKAction.follow(path, duration: 0)
    _ = SKAction.follow(path, speed: 1)
    _ = SKAction.follow(path, asOffset: true, orientToPath: false, duration: 0)
    _ = SKAction.follow(path, asOffset: false, orientToPath: true, speed: 1)
    let node = SKNode()
    let root = SKNode()
    _ = SKAction.reach(to: CGPoint(x: 1, y: 1), rootNode: root, duration: 0)
    _ = SKAction.reach(to: CGPoint(x: 1, y: 1), rootNode: root, velocity: 1)
    _ = SKAction.reach(to: node, rootNode: root, duration: 0)
    _ = SKAction.reach(to: node, rootNode: root, velocity: 1)
    let warp = SKWarpGeometry()
    _ = SKAction.warp(to: warp, duration: 0)
    _ = SKAction.animate(withWarps: [warp], times: [0 as NSNumber])
    _ = SKAction.animate(withWarps: [warp], times: [0 as NSNumber], restore: true)
    let action = SKAction.wait(forDuration: 1)
    action.duration = 0.5
    action.speed = 2
    action.timingMode = .easeIn
    action.timingFunction = { $0 }
    _ = action.timingFunction(0.5)
    var queued = false
    let queue = DispatchQueue(label: "spritekit-action-queue")
    let scene = SKScene(size: CGSize(width: 8, height: 8))
    scene.addChild(node)
    node.run(SKAction.run({ queued = true }, queue: queue))
    scene.update(0)
    precondition(queued)
}
