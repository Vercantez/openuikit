import Accelerate
import Foundation

private func checkLane(_ actual: Float, _ expected: Float, _ tol: Float = 0.00001) {
    precondition(abs(actual - expected) <= tol)
}

func testVForceSIMDTrig() {
    let half = vFloat(0.5, 0.5, 0.5, 0.5)
    let ac = vacosf(half)
    checkLane(ac[0], 1.0471976)
    let ash = vacoshf(vFloat(1, 2, 1, 2))
    checkLane(ash[0], 0)
    checkLane(vasinf(vFloat(0, 0, 0, 0))[0], 0)
    checkLane(vasinhf(vFloat(0, 1, 0, 1))[1], Foundation.asinh(1))
    checkLane(vatanf(vFloat(1, 1, 1, 1))[0], Float.pi / 4)
    checkLane(vatanhf(vFloat(0.5, 0.5, 0.5, 0.5))[0], Foundation.atanh(0.5))
    let a2 = vatan2f(vFloat(1, 0, -1, 0), vFloat(1, 1, 1, 1))
    checkLane(a2[0], 0.7853982)
    checkLane(a2[1], 0)
    checkLane(a2[2], -0.7853982)
    checkLane(vsinf(vFloat(0, 0, 0, 0))[0], 0)
    checkLane(vcosf(vFloat(0, 0, 0, 0))[0], 1)
    checkLane(vtanf(vFloat(0, 0, 0, 0))[0], 0)
    checkLane(vsinpif(vFloat(0.5, 0.5, 0.5, 0.5))[0], 1)
    checkLane(vcospif(vFloat(0.5, 0.5, 0.5, 0.5))[0], 0)
    checkLane(vtanpif(vFloat(0.25, 0.25, 0.25, 0.25))[0], 1)
    checkLane(vsinhf(vFloat(0, 0, 0, 0))[0], 0)
    checkLane(vcoshf(vFloat(0, 0, 0, 0))[0], 1)
    checkLane(vtanhf(vFloat(1, 1, 1, 1))[0], Foundation.tanh(1))
    // vfp.h: vsincosf returns cosine and stores sine through the pointer.
    var sine = vFloat(0, 0, 0, 0)
    let cosine = vsincosf(vFloat(0.5, 0.5, 0.5, 0.5), &sine)
    checkLane(cosine[0], 0.87758255)
    checkLane(sine[0], 0.47942555)
}

func testVForceSIMDExpLog() {
    checkLane(vexpf(vFloat(0, 1, 0, 1))[0], 1)
    checkLane(vexpf(vFloat(0, 1, 0, 1))[1], Foundation.exp(1))
    let e2 = vexp2f(vFloat(3, 0, 3, 0))
    checkLane(e2[0], 8)
    checkLane(vexpm1f(vFloat(0, 0, 0, 0))[0], 0)
    checkLane(vlogf(vFloat(1, 2.7182817, 1, 1))[0], 0)
    let l2 = vlog2f(vFloat(8, 1, 8, 1))
    checkLane(l2[0], 3)
    let l10 = vlog10f(vFloat(100, 1, 100, 1))
    checkLane(l10[0], 2)
    checkLane(vlog1pf(vFloat(0, 0, 0, 0))[0], 0)
    let lb = vlogbf(vFloat(8, 0.75, 1, 0.5))
    checkLane(lb[0], 3)
    checkLane(lb[1], -1)
    checkLane(lb[2], 0)
    checkLane(lb[3], -1)
    let pw = vpowf(vFloat(2, 0, 2, 0), vFloat(10, 0, 10, 0))
    checkLane(pw[0], 1024)
    checkLane(pw[1], 1)
    let ip = vipowf(vFloat(2, 3, 4, 5), vSInt32(3, 2, -1, 0))
    checkLane(ip[0], 8)
    checkLane(ip[1], 9)
    checkLane(ip[2], 0.25)
    checkLane(ip[3], 1)
    let sc = vscalbf(vFloat(1.5, 1.5, 1.5, 1.5), vSInt32(2, -1, 0, 3))
    checkLane(sc[0], 6)
    checkLane(sc[1], 0.75)
    checkLane(sc[2], 1.5)
    checkLane(sc[3], 12)
    let sq = vsqrtf(vFloat(4, 9, 0.25, 1))
    checkLane(sq[0], 2)
    checkLane(sq[1], 3)
    checkLane(sq[2], 0.5)
    checkLane(vrsqrtf(vFloat(4, 4, 4, 4))[0], 0.5)
    checkLane(vrecf(vFloat(2, 4, 2, 4))[0], 0.5)
    let dv = vdivf(vFloat(1, 3, 1, 3), vFloat(2, 2, 2, 2))
    checkLane(dv[0], 0.5)
    checkLane(dv[1], 1.5)
}

func testVForceSIMDRounding() {
    let up = vceilf(vFloat(1.2, -1.2, 2.0, -2.0))
    checkLane(up[0], 2)
    checkLane(up[1], -1)
    let dn = vfloorf(vFloat(1.7, -1.7, 2.0, -2.0))
    checkLane(dn[0], 1)
    checkLane(dn[1], -2)
    let tr = vtruncf(vFloat(1.7, -1.7, 2.5, -2.5))
    checkLane(tr[0], 1)
    checkLane(tr[1], -1)
    checkLane(tr[2], 2)
    checkLane(tr[3], -2)
    // Ties to even per vfp.h.
    let nr = vnintf(vFloat(2.5, 1.5, -2.5, -1.5))
    checkLane(nr[0], 2)
    checkLane(nr[1], 2)
    checkLane(nr[2], -2)
    checkLane(nr[3], -2)
    let ab = vfabsf(vFloat(-3, 3, -0.0, 0))
    checkLane(ab[0], 3)
    checkLane(ab[1], 3)
    let cs = vcopysignf(vFloat(1, -1, 1, -1), vFloat(-5, 5, -5, 5))
    checkLane(cs[0], -1)
    checkLane(cs[1], 1)
    checkLane(cs[2], -1)
    checkLane(cs[3], 1)
    let nx = vnextafterf(vFloat(1, 0, 0, 0), vFloat(2, 0, 0, 0))
    precondition(nx[0] == Float(1).nextUp)
    precondition(nx[1] == 0)
    let fm = vfmodf(vFloat(5.3, -5.3, 5.3, -5.3), vFloat(2, 2, 2, 2))
    checkLane(fm[0], 1.3, 0.00001)
    checkLane(fm[1], -1.3, 0.00001)
    let rm = vremainderf(vFloat(5.3, -5.3, 5.3, -5.3), vFloat(2, 2, 2, 2))
    checkLane(rm[0], -0.7, 0.00001)
    checkLane(rm[1], 0.7, 0.00001)
    // IEEE remainder plus 7 low-order quotient bits with the sign of x/y.
    var quo = vUInt32(0, 0, 0, 0)
    var lhs = vFloat(5.3, -5.3, 7, 5.3)
    var rhs = vFloat(2, 2, 3, -2)
    let rq = vremquof(lhs, rhs, &quo)
    checkLane(rq[0], -0.7, 0.00001)
    precondition(quo[0] == 3)
    precondition(quo[1] == UInt32(bitPattern: -3))
    precondition(quo[2] == 2)
    precondition(quo[3] == UInt32(bitPattern: -3))
    // Apple FP_xxx codes: NAN=1, INFINITE=2, ZERO=3, NORMAL=4, SUBNORMAL=5.
    lhs = vFloat(1, Float.infinity, 0, Float.nan)
    let cl = vclassifyf(lhs)
    precondition(cl[0] == 4)
    precondition(cl[1] == 2)
    precondition(cl[2] == 3)
    precondition(cl[3] == 1)
    rhs = vFloat(-Float.infinity, -0.0, Float.leastNonzeroMagnitude, 1e10)
    let cl2 = vclassifyf(rhs)
    precondition(cl2[0] == 2)
    precondition(cl2[1] == 3)
    precondition(cl2[2] == 5)
    precondition(cl2[3] == 4)
    let sb = vsignbitf(vFloat(1, -1, -0.0, Float.infinity))
    precondition(sb[0] == 0)
    precondition(sb[1] == 1)
    precondition(sb[2] == 1)
    precondition(sb[3] == 0)
    var table: [UInt32] = [10, 20, 30, 40]
    let gathered = vtablelookup(vSInt32(3, 0, 2, 1), &table)
    precondition(gathered[0] == 40)
    precondition(gathered[1] == 10)
    precondition(gathered[2] == 30)
    precondition(gathered[3] == 20)
}
