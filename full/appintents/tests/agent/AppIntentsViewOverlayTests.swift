import Foundation
import AppIntents

// Identity View-overlay batches: each leftover SwiftUI modifier is
// invoked on this slug's View types plus EmptyView. Linux renders
// EmptyView; these calls pin the no-op identity behavior without
// inventing layout. No daemon, no waiting, no suspension point.

private struct OverlayProbeIntent: AppIntent {
    static var title: LocalizedStringResource { "Overlay Probe" }
    func perform() async throws -> some IntentResult & ReturnsValue<String> {
        .result(value: "overlay")
    }
}

