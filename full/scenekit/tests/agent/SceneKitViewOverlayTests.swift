func testSceneViewOptionsWitnesses() {
    var rolling: SceneView.Options = [.rendersContinuously, .allowsCameraControl]
    let cameraOnly: SceneView.Options = [.allowsCameraControl]
    precondition(rolling != cameraOnly)
    precondition(!(rolling == cameraOnly))
    precondition(rolling.isSuperset(of: cameraOnly))
    precondition(cameraOnly.isSubset(of: rolling))
    precondition(cameraOnly.isStrictSubset(of: rolling))
    precondition(rolling.isStrictSuperset(of: cameraOnly))
    precondition(!rolling.isEmpty)
    precondition(SceneView.Options().isEmpty)
    precondition(!rolling.isDisjoint(with: cameraOnly))
    precondition(rolling.isDisjoint(with: [.jitteringEnabled]))
    precondition(rolling.subtracting(cameraOnly) == [.rendersContinuously])
    rolling.subtract(cameraOnly)
    precondition(rolling == [.rendersContinuously])
    _ = rolling.union(cameraOnly)
    _ = rolling.intersection(cameraOnly)
    _ = rolling.symmetricDifference(cameraOnly)
    rolling.formUnion(cameraOnly)
    precondition(rolling == [.rendersContinuously, .allowsCameraControl])
    rolling.formIntersection(cameraOnly)
    precondition(rolling == cameraOnly)
    rolling.formSymmetricDifference([.rendersContinuously, .allowsCameraControl])
    precondition(rolling == [.rendersContinuously])
    let literal: SceneView.Options = [.rendersContinuously, .jitteringEnabled]
    precondition(literal.contains(.rendersContinuously))
    let seeds: [SceneView.Options] = [.allowsCameraControl, .jitteringEnabled]
    let fromSequence = SceneView.Options(seeds)
    precondition(fromSequence == [.allowsCameraControl, .jitteringEnabled])
    let empty = SceneView.Options()
    precondition(empty == [])
    var mutable = SceneView.Options()
    let inserted = mutable.insert(.temporalAntialiasingEnabled)
    precondition(inserted.inserted)
    precondition(mutable.contains(.temporalAntialiasingEnabled))
    _ = mutable.update(with: .autoenablesDefaultLighting)
    precondition(mutable.contains(.autoenablesDefaultLighting))
    _ = mutable.remove(.temporalAntialiasingEnabled)
    precondition(!mutable.contains(.temporalAntialiasingEnabled))
}
